#!/usr/bin/env bash
# Renders the T3 provider config for CLIProxyAPI, then runs `t3 serve`.
#
#   serve [t3 serve flags...]  render config, then exec `t3 serve` (default)
#   render                     render config and exit (dry run / debugging)
#   anything else              exec it unchanged (bash, t3 doctor, ...)
#
# Managed on every boot, so env changes and key rotations take effect on
# restart: the claude-cliproxy and codex-cliproxy entries in
# $T3CODE_HOME/userdata/settings.json, defaultModelSelection, and the
# codex-cliproxy config.toml. The built-in codex and claudeAgent instances are
# disabled on every boot, along with other non-proxy instances and project
# provider overrides. Unrelated UI settings are kept. Reference: docs/t3-driver-deploy.md.
set -euo pipefail

die() {
  echo "t3-sidecar: $*" >&2
  exit 64
}

# Prints $NAME, or the contents of the file named by $NAME_FILE.
read_secret() {
  local name="$1"
  local file_var="${name}_FILE"
  local direct="${!name:-}"
  local file="${!file_var:-}"
  if [[ -n "$direct" && -n "$file" ]]; then
    die "set ${name} or ${file_var}, not both"
  fi
  if [[ -n "$file" ]]; then
    [[ -r "$file" ]] || die "${file_var} is not a readable file: ${file}"
    # $(<file) drops trailing newlines, which secret files usually end with.
    printf '%s' "$(<"$file")"
    return
  fi
  printf '%s' "$direct"
}

toml_string() {
  jq --null-input --arg value "$1" '$value'
}

render_config() {
  : "${T3CODE_HOME:?T3CODE_HOME must be set}"
  local base_url="${CLIPROXYAPI_BASE_URL:-}"
  [[ -n "$base_url" ]] || die "CLIPROXYAPI_BASE_URL is required (e.g. https://cliproxyapi.ai.roxasroot.net)"
  base_url="${base_url%/}"

  local api_key
  api_key="$(read_secret CLIPROXYAPI_API_KEY)"
  [[ -n "$api_key" ]] || die "CLIPROXYAPI_API_KEY or CLIPROXYAPI_API_KEY_FILE is required"
  # Codex reads the bearer through `env_key`, so it never lands on disk. Every
  # agent T3 starts inherits this environment.
  export CLIPROXYAPI_API_KEY="$api_key"
  unset CLIPROXYAPI_API_KEY_FILE
  # Claude Code prefers ANTHROPIC_API_KEY over ANTHROPIC_AUTH_TOKEN; keep a
  # stray one from bypassing the proxy (same as toolbox's claudex wrapper).
  unset ANTHROPIC_API_KEY ANTHROPIC_AUTH_TOKEN ANTHROPIC_BASE_URL \
    CLAUDE_CODE_OAUTH_TOKEN CLAUDE_CODE_API_KEY_HELPER \
    CLAUDE_CODE_USE_BEDROCK CLAUDE_CODE_USE_VERTEX CLAUDE_CODE_USE_FOUNDRY \
    OPENAI_API_KEY OPENAI_BASE_URL OPENAI_ACCESS_TOKEN
  export CLIPROXYAPI_BASE_URL="$base_url"

  local codex_home="${T3_CODEX_HOME:-${T3CODE_HOME}/codex-cliproxy}"
  local claude_home="${T3_CLAUDE_CONFIG_DIR:-${T3CODE_HOME}/claude-cliproxy}"
  local codex_model="${T3_CODEX_MODEL:-gpt-6-sol}"
  local codex_effort="${T3_CODEX_REASONING_EFFORT:-high}"
  local default_instance="${T3_DEFAULT_PROVIDER_INSTANCE:-claude-cliproxy}"
  local default_model="${T3_DEFAULT_MODEL:-claude-opus-5-5}"

  case "$default_instance" in
    claude-cliproxy|codex-cliproxy) ;;
    *) die "T3_DEFAULT_PROVIDER_INSTANCE must be claude-cliproxy or codex-cliproxy" ;;
  esac
  local runtime_mode="${T3_RUNTIME_MODE:-auto}"
  case "$runtime_mode" in
    auto|full-access) ;;
    *) die "T3_RUNTIME_MODE must be auto or full-access" ;;
  esac

  umask 077
  mkdir -p "${T3CODE_HOME}/userdata" "$codex_home" "$claude_home"

  local codex_config="${codex_home}/config.toml"
  {
    echo "# Generated by t3-sidecar-entrypoint on every start; edits are overwritten."
    echo "# Add settings through T3_CODEX_CONFIG_EXTRA_FILE instead."
    echo "model = $(toml_string "$codex_model")"
    echo 'model_provider = "cliproxyapi"'
    echo "model_reasoning_effort = $(toml_string "$codex_effort")"
    echo 'approval_policy = "never"'
    echo 'sandbox_mode = "danger-full-access"'
    echo
    echo '[model_providers.cliproxyapi]'
    echo 'name = "CLIProxyAPI"'
    echo "base_url = $(toml_string "${base_url}/v1")"
    echo 'wire_api = "responses"'
    echo 'env_key = "CLIPROXYAPI_API_KEY"'
    if [[ -n "${T3_CODEX_CONFIG_EXTRA_FILE:-}" ]]; then
      [[ -r "$T3_CODEX_CONFIG_EXTRA_FILE" ]] ||
        die "T3_CODEX_CONFIG_EXTRA_FILE is not a readable file: ${T3_CODEX_CONFIG_EXTRA_FILE}"
      echo
      echo "# From ${T3_CODEX_CONFIG_EXTRA_FILE}"
      cat "$T3_CODEX_CONFIG_EXTRA_FILE"
    fi
  } >"${codex_config}.tmp"
  mv -f "${codex_config}.tmp" "$codex_config"

  local settings="${T3CODE_HOME}/userdata/settings.json"
  local current='{}'
  if [[ -s "$settings" ]]; then
    current="$(<"$settings")"
    jq --exit-status 'type == "object"' >/dev/null <<<"$current" ||
      die "${settings} is not a JSON object; fix or remove it"
  fi
  jq \
    --arg base_url "$base_url" \
    --arg api_key "$api_key" \
    --arg codex_home "$codex_home" \
    --arg claude_home "$claude_home" \
    --arg default_instance "$default_instance" \
    --arg default_model "$default_model" \
    --arg runtime_mode "$runtime_mode" \
    '
    .providerInstances = (((.providerInstances // {}) | with_entries(.value.enabled = false)) + {
      "claude-cliproxy": {
        driver: "claudeAgent",
        displayName: "Claude (CLIProxyAPI)",
        enabled: true,
        environment: [
          { name: "ANTHROPIC_BASE_URL", value: $base_url, sensitive: false },
          { name: "ANTHROPIC_AUTH_TOKEN", value: $api_key, sensitive: true },
          { name: "CLAUDE_CODE_DISABLE_NONESSENTIAL_TRAFFIC", value: "1", sensitive: false }
        ],
        config: { homePath: $claude_home }
      },
      "codex-cliproxy": {
        driver: "codex",
        displayName: "Codex (CLIProxyAPI)",
        enabled: true,
        config: { homePath: $codex_home }
      }
    })
    | .providerInstances.codex = { driver: "codex", enabled: false }
    | .providerInstances.claudeAgent = { driver: "claudeAgent", enabled: false }
    | .defaultRuntimeMode = $runtime_mode
    | .textGenerationModelSelection = { instanceId: "codex-cliproxy", model: "gpt-6-luna" }
    | .sourceControlWriterModelSelection = null
    | .reviewGuideModelSelection = null
    | .projectProviderInstanceOverrides = {}
    | .projectSettingsOverrides = {}
    | .defaultModelSelection = { instanceId: $default_instance, model: $default_model }
    ' <<<"$current" >"${settings}.tmp"
  mv -f "${settings}.tmp" "$settings"

  echo "t3-sidecar: rendered ${settings} and ${codex_config} for ${base_url}" >&2
}

case "${1:-serve}" in
  serve)
    [[ $# -gt 0 ]] && shift
    render_config
    echo "t3-sidecar: t3 ${T3_SIDECAR_VERSION_T3:-?}, codex ${T3_SIDECAR_VERSION_CODEX:-?}, claude ${T3_SIDECAR_VERSION_CLAUDE:-?}" >&2
    exec t3 serve --no-browser "$@" "${T3_WORKSPACE_ROOT:-/app/workspaces}"
    ;;
  render)
    render_config
    ;;
  *)
    exec "$@"
    ;;
esac
