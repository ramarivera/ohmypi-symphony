/**
 * Gateway-owned `t3 serve` per session. Each daemon runs under the session's
 * worker uid with the OMP worker env allowlist, keeps its state inside the
 * session's private workspace, listens on loopback only, and accepts only a
 * bearer issued for its own state directory.
 *
 * Loopback is shared by every uid in the container, so the port alone is not
 * a boundary. Before the bearer leaves the gateway (at launch and on every
 * reconnect) the launcher checks in /proc/net/tcp{,6} that the session uid
 * owns every listener on the port. A squatter from another session fails the
 * launch instead of receiving the token.
 */
