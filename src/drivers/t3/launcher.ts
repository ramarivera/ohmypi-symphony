/** uids of every listening TCP socket on `port`, from /proc/net/tcp and tcp6. */
export const listenerOwnerUids = (
  tables: ReadonlyArray<string>,
  port: number,
): ReadonlyArray<number> => {
  const hexPort = port.toString(16).toUpperCase().padStart(4, "0");
  const owners: number[] = [];
  for (const table of tables)
    for (const line of table.split("\n").slice(1)) {
      const fields = line.trim().split(/\s+/u);
      // sl local rem st tx:rx tr:when retrnsmt uid ...
      if (fields.length < 8 || fields[3] !== "0A") continue;
      if (fields[1]?.split(":").at(-1)?.toUpperCase() !== hexPort) continue;
      const uid = Number(fields[7]);
      if (Number.isSafeInteger(uid)) owners.push(uid);
    }
  return owners;
};

const readProcNetTcp = (): ReadonlyArray<string> | undefined => {
  try {
    const tables = [readFileSync("/proc/net/tcp", "utf8")];
    try {
      tables.push(readFileSync("/proc/net/tcp6", "utf8"));
    } catch {
      // IPv6 can be disabled in the container; IPv4 is what T3 binds.
    }
    return tables;
  } catch {
    return undefined;
  }
};

export type ListenerState = "free" | "owned" | "foreign" | "unknown";

/** Loopback ports for launched daemons, unique within this gateway. */
export class T3PortPool {
  private readonly inUse = new Set<number>();
  constructor(
    readonly base: number,
    readonly count: number,
  ) {}
  allocate(isFree: (port: number) => boolean): number | undefined {
    for (let port = this.base; port < this.base + this.count; port++) {
      if (this.inUse.has(port) || !isFree(port)) continue;
      this.inUse.add(port);
      return port;
    }
    return undefined;
  }
  release(port: number): void {
    this.inUse.delete(port);
  }
}

const IssuedSession = Schema.Struct({ token: Schema.String });
const decodeIssuedSession = Schema.decodeUnknownEffect(
  Schema.fromJsonString(IssuedSession),
);

export interface T3LaunchInput {
  readonly sessionId: string;
  readonly cwd: string;
  /** The session's worker uid; undefined only in native same-uid mode. */
  readonly workerUid: string | undefined;
  readonly launch: T3LaunchConfig;
  readonly ports: T3PortPool;
  /** Allowlisted worker environment with a per-session HOME. */
  readonly environment: Record<string, string>;
  /** CLIProxyAPI base URL and client key, injected only into `t3 serve`. */
  readonly modelEnvironment: Record<string, string>;
  readonly settings: T3LaunchSettings;
  /** Writes the settings as the worker uid (workspace-worker `t3-config`). */
  readonly writeSettings: (settings: T3LaunchSettings) => Promise<void>;
  /** Test seam; production reads /proc/net/tcp{,6}. */
  readonly readListeners?: () => ReadonlyArray<string> | undefined;
  readonly pollIntervalMs?: number;
  readonly stopTimeoutMs?: number;
}

export interface T3Daemon extends T3Endpoint {
  readonly port: number;
  readonly pid: number;
  readonly exited: Promise<number>;
}

const launchError = (message: string) => new RpcSpawnError({ message });

// Startup prints a one-time pairing code; never keep it in diagnostics.
const SECRET_LINE = /token|pairing|bearer|authorization/iu;

const drain = (
  stream: ReadableStream<Uint8Array> | null | undefined,
  tail: string[],
): void => {
  if (!stream) return;
  void (async () => {
    const decoder = new TextDecoder();
    let pending = "";
    for await (const chunk of stream) {
      pending += decoder.decode(chunk, { stream: true });
      const lines = pending.split("\n");
      pending = lines.pop() ?? "";
      for (const line of lines) {
        if (line.trim() === "" || SECRET_LINE.test(line)) continue;
        tail.push(line.slice(0, 300));
        if (tail.length > 20) tail.shift();
      }
    }
  })().catch(() => undefined);
};

/** Starts the session's daemon in the caller's scope; closing it stops the process group. */
export const launchT3Daemon = Effect.fn("T3Launcher.launch")(function* (
  input: T3LaunchInput,
): Effect.fn.Return<T3Daemon, RpcSpawnError, Scope.Scope> {
  const readListeners = input.readListeners ?? readProcNetTcp;
  const expectedUid =
    input.workerUid === undefined
      ? process.getuid?.()
      : Number(input.workerUid);
  const listenerState = (port: number): ListenerState => {
    const tables = readListeners();
    if (tables === undefined) return "unknown";
    const owners = listenerOwnerUids(tables, port);
    if (owners.length === 0) return "free";
    return owners.every((uid) => uid === expectedUid) ? "owned" : "foreign";
  };
  // Isolation depends on the ownership check; only native dev may skip it.
  if (input.workerUid !== undefined && readListeners() === undefined)
    return yield* launchError(
      "T3 launcher cannot verify loopback listener ownership without /proc/net/tcp",
    );
  const paths = t3SessionPaths(input.cwd);
  const environment = {
    ...input.environment,
    HOME: paths.home,
    T3CODE_HOME: paths.t3Home,
    T3CODE_NO_BROWSER: "true",
    T3CODE_TELEMETRY_ENABLED: "false",
    DISABLE_AUTOUPDATER: "1",
    CLAUDE_CODE_DISABLE_NONESSENTIAL_TRAFFIC: "1",
  };
  const command = (args: ReadonlyArray<string>) =>
    workerIdentityCommand([input.launch.cliPath, ...args], input.workerUid);

  yield* Effect.tryPromise({
    try: () => input.writeSettings(input.settings),
    catch: (error) =>
      launchError(
        `Could not write T3 settings: ${error instanceof Error ? error.message : String(error)}`,
      ),
  });

  // Issued offline into this daemon's own state; valid nowhere else.
  const issued = yield* Effect.tryPromise({
    try: async () => {
      const child = Bun.spawn(
        command([
          "auth",
          "session",
          "issue",
          "--base-dir",
          paths.t3Home,
          ...T3_LAUNCH_SCOPES.flatMap((scope) => ["--scope", scope]),
          "--ttl",
          "30d",
          "--label",
          `Partitura ${input.sessionId}`.slice(0, 80),
          "--json",
        ]),
        {
          cwd: input.cwd,
          env: environment,
          stdin: "ignore",
          stdout: "pipe",
          stderr: "ignore",
        },
      );
      const timer = setTimeout(
        () => child.kill("SIGKILL"),
        input.launch.launchTimeoutMs,
      );
      try {
        const [code, stdout] = await Promise.all([
          child.exited,
          new Response(child.stdout).text(),
        ]);
        if (code !== 0) throw new Error(`exit ${code}`);
        return stdout;
      } finally {
        clearTimeout(timer);
      }
    },
    catch: (error) =>
      launchError(
        `Could not issue the T3 session bearer: ${error instanceof Error ? error.message : String(error)}`,
      ),
  }).pipe(
    Effect.flatMap((stdout) =>
      decodeIssuedSession(stdout.trim()).pipe(
        Effect.mapError(() =>
          launchError("T3 returned an unreadable session bearer"),
        ),
      ),
    ),
  );
  const token = Redacted.make(issued.token);

  const port = input.ports.allocate((candidate) => {
    const state = listenerState(candidate);
    return state === "free" || state === "unknown";
  });
  if (port === undefined)
    return yield* launchError(
      "No free T3 loopback port; raise T3_PORT_COUNT or wait for a session to end",
    );
  yield* Effect.addFinalizer(() =>
    Effect.sync(() => input.ports.release(port)),
  );

  const tail: string[] = [];
  const stopTimeoutMs = input.stopTimeoutMs ?? 5_000;
  const child = yield* Effect.acquireRelease(
    Effect.try({
      try: (): Subprocess<"ignore", "pipe", "pipe"> =>
        Bun.spawn(
          command([
            "serve",
            "--host",
            "127.0.0.1",
            "--port",
            String(port),
            "--base-dir",
            paths.t3Home,
            input.cwd,
          ]),
          {
            cwd: input.cwd,
            env: { ...environment, ...input.modelEnvironment },
            stdin: "ignore",
            stdout: "pipe",
            stderr: "pipe",
            detached: detachedProcessGroup,
          },
        ),
      catch: () => launchError("Could not start t3 serve"),
    }),
    (process) =>
      Effect.promise(async () => {
        signalProcessTree(process, "SIGTERM");
        const exited = await Promise.race([
          process.exited.then(() => true),
          Bun.sleep(stopTimeoutMs).then(() => false),
        ]);
        // Providers can outlive a graceful stop; the group shares their fate.
        signalProcessTree(process, "SIGKILL");
        if (!exited) await Promise.race([process.exited, Bun.sleep(2_000)]);
      }),
  );
  drain(child.stdout, tail);
  drain(child.stderr, tail);

  const baseUrl = new URL(`http://127.0.0.1:${port}`);
  const deadline =
    (yield* Clock.currentTimeMillis) + input.launch.launchTimeoutMs;
  const pollIntervalMs = input.pollIntervalMs ?? 200;
  for (;;) {
    if (child.exitCode !== null || child.signalCode !== null)
      return yield* launchError(
        `t3 serve exited before it was ready${tail.length > 0 ? `: ${tail.slice(-5).join(" | ")}` : ""}`,
      );
    const state = listenerState(port);
    if (state === "foreign")
      return yield* launchError(
        `T3 loopback port ${port} is held by another identity; refusing to send the session bearer`,
      );
    if (state === "owned" || state === "unknown") {
      const ready = yield* Effect.promise(() =>
        fetch(new URL("/.well-known/t3/environment", baseUrl), {
          signal: AbortSignal.timeout(2_000),
        })
          .then((response) => response.ok)
          .catch(() => false),
      );
      if (ready) break;
    }
    if ((yield* Clock.currentTimeMillis) >= deadline)
      return yield* launchError(
        `t3 serve was not ready within ${input.launch.launchTimeoutMs}ms`,
      );
    yield* Effect.sleep(pollIntervalMs);
  }

  return {
    baseUrl,
    port,
    pid: child.pid,
    exited: child.exited,
    // Re-verified before every connect: a restarted listener must still be ours.
    token: Effect.suspend(() => {
      const state = listenerState(port);
      return state === "owned" ||
        (state === "unknown" && input.workerUid === undefined)
        ? Effect.succeed(token)
        : Effect.fail(
            new T3RpcError({
              reason: "auth",
              method: "token",
              sent: false,
              message: `T3 loopback port ${port} is not held by this session's daemon`,
            }),
          );
    }),
  } satisfies T3Daemon;
});

/**
 * A T3 driver whose daemon lives exactly as long as the opened session: the
 * daemon starts in the session scope, so stop/close terminates it after the
 * session's own finalizers have run.
 */
export const launchedT3Driver = (
  launch: Effect.Effect<T3Daemon, RpcSpawnError, Scope.Scope>,
  options: (endpoint: T3Endpoint) => T3DriverOptions,
): AgentDriver => ({
  kind: "t3",
  capabilities: T3_CAPABILITIES,
  probe: Effect.fail(
    new DriverError({
      driver: "t3",
      operation: "probe",
      reason: "unsupported",
      submission: "not-submitted",
      message: "Launched T3 daemons exist only while a session is open",
    }),
  ),
  open: (input) =>
    Effect.gen(function* () {
      const daemon = yield* launch.pipe(
        Effect.mapError(
          (error) =>
            new DriverError({
              driver: "t3",
              operation: "launch",
              reason: "unavailable",
              submission: "not-submitted",
              message: error.message,
            }),
        ),
      );
      return yield* makeT3Driver(options(daemon)).open(input);
    }),
});
